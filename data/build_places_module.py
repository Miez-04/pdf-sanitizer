"""
data/build_places_module.py

Generates regex_engine/malaysia_places.py from the project's own postal
registry (data/raw/postalcode.json), so the address heuristic can check that a
"City, State" pair is a REAL pair ("Kota Bharu, Kelantan" yes, "Kota Bharu,
Selangor" no) without reading any data file at run time.

    python -m data.build_places_module
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

REGISTRY = Path("data/raw/postalcode.json")
OUT = Path("regex_engine/malaysia_places.py")
_STRIP = ",.;:()"

# state spellings seen on real documents -> canonical lowercase state
STATE_VARIANTS = {
    "johor": ["Johor", "Johor Darul Ta'zim", "Johor Darul Takzim"],
    "kedah": ["Kedah", "Kedah Darul Aman"],
    "kelantan": ["Kelantan", "Kelantan Darul Naim"],
    "melaka": ["Melaka", "Malacca"],
    "negeri sembilan": ["Negeri Sembilan", "Negeri Sembilan Darul Khusus", "N. Sembilan", "N.Sembilan", "N9"],
    "pahang": ["Pahang", "Pahang Darul Makmur"],
    "perak": ["Perak", "Perak Darul Ridzuan"],
    "perlis": ["Perlis", "Perlis Indera Kayangan"],
    "pulau pinang": ["Pulau Pinang", "Penang", "P. Pinang"],
    "sabah": ["Sabah"],
    "sarawak": ["Sarawak"],
    "selangor": ["Selangor", "Selangor Darul Ehsan"],
    "terengganu": ["Terengganu", "Terengganu Darul Iman"],
    "kuala lumpur": ["Kuala Lumpur", "KL", "WP Kuala Lumpur", "W.P. Kuala Lumpur",
                     "Wilayah Persekutuan Kuala Lumpur", "WP KL", "W.P. KL"],
    "putrajaya": ["Putrajaya", "WP Putrajaya", "W.P. Putrajaya", "Wilayah Persekutuan Putrajaya"],
    "labuan": ["Labuan", "WP Labuan", "W.P. Labuan", "Wilayah Persekutuan Labuan"],
    "wp": ["Wilayah Persekutuan", "W.P.", "WP"],  # federal territory, not specific
}
CITY_ALIASES = {"georgetown": "pulau pinang", "george town": "pulau pinang", "johor baru": "johor"}


def _norm(text: str) -> tuple[str, ...]:
    return tuple(w.strip(_STRIP).lower() for w in text.split() if w.strip(_STRIP))


def main() -> None:
    data = json.loads(REGISTRY.read_text(encoding="utf-8"))["data"]
    cities: dict[tuple[str, ...], set[str]] = defaultdict(set)
    for e in data:
        state = e["state"].lower().replace("wp ", "")  # "WP Kuala Lumpur" -> "kuala lumpur"
        cities[_norm(e["city"])].add(state)
    for alias, state in CITY_ALIASES.items():
        cities[_norm(alias)].add(state)
    lines = [
        '"""AUTO-GENERATED by data/build_places_module.py from data/raw/postalcode.json. Do not edit.',
        "",
        "CITY_STATES: lowercase city words -> the lowercase states that city belongs to.",
        "STATE_PHRASES: lowercase state spelling (words) -> canonical state ('wp' = a federal",
        'territory written without its name). Tokens are compared after .strip(",.;:()").lower().',
        '"""',
        "",
        "CITY_STATES: dict[tuple[str, ...], frozenset[str]] = {",
    ]
    for k in sorted(cities):
        lines.append(f"    {k!r}: frozenset({sorted(cities[k])!r}),")
    lines += ["}", "", "STATE_PHRASES: dict[tuple[str, ...], str] = {"]
    seen: dict[tuple[str, ...], str] = {}
    for canon, variants in STATE_VARIANTS.items():
        for v in variants:
            seen[_norm(v)] = canon
    for k in sorted(seen):
        lines.append(f"    {k!r}: {seen[k]!r},")
    lines += ["}", "", f"MAX_CITY_WORDS = {max(len(k) for k in cities)}",
              f"MAX_STATE_WORDS = {max(len(k) for k in seen)}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}: {len(cities)} cities, {len(seen)} state spellings")


if __name__ == "__main__":
    main()
